// 응답을 보낸 뒤로 미루는 자리. **밖으로 나가는 일은 전부 여기를 지난다.**
//
// ── 왜 맨 프로미스로는 안 되나 ──────────────────────────────
// 서버리스(D-018)에서는 응답이 나간 뒤의 실행이 보장되지 않는다 — Vercel은 "반드시
// 끝나야 하는 일(DB 쓰기 등)은 `waitUntil`이나 `after`로 감싸라, 감싸지 않은 일은
// 유실된다"고 적었다
// (<https://vercel.com/docs/functions/functions-api-reference> · 확인 2026-08-15).
// Next의 `after()`가 그 `waitUntil`을 대신 잡아주고, 그게 이 보장을 사는 유일한
// 경로다 (<https://nextjs.org/docs/app/api-reference/functions/after> · 같은 날 확인).
//
// `void notify(...)`로 두면 응답이 나간 뒤 인스턴스가 정리되면서 **조용히 사라진다.**
// 09 §2가 "발송은 비동기다 · 실패하면 재시도 1회 후 로그만 남기고 포기"라고 정한 것은
// **발송이 실패하는 경우**다. 실행 자체가 없으면 로그도 없고, 그러면 메일이 나가지
// 않은 사실조차 관측되지 않는다. 텔레그램은 심각 카테고리 신고를 새벽에 알리는 유일한
// 수단이라(09 §3) 조용한 유실이 곧 S-5 콘텐츠가 밤새 떠 있는 것이다.
//
// ── 감싸는 것은 실행을 보장하는 것이지 실패를 구제하는 것이 아니다 ──
// 09 §2의 실패 정책은 그대로다. 던진 것은 여기서 **로그만 남기고 삼킨다** — 응답은
// 이미 나갔고 예외를 받아줄 호출자가 없다. 재시도는 발송 함수 안쪽의 일이다.

import { after } from "next/server";

/**
 * `task`를 **응답이 나간 뒤에** 돌린다. 아무것도 돌려주지 않는다 — 결과를 기다리는
 * 순간 이 함수를 쓸 이유가 없어진다.
 *
 * `label`은 로그에만 쓴다. 실패가 어느 발송이었는지 여기서 밝히지 못하면 밝힐 곳이
 * 없다. 스택은 이미 요청 밖이라 어느 표면에서 왔는지가 남지 않는다.
 *
 * **요청 스코프 밖에서는 `after()`가 던진다(`E468`).** 테스트가 라우트 핸들러를 Next
 * 런타임 없이 직접 부르는 경우가 그것이고, 그때는 미룰 곳이 없으니 그대로 띄운다 —
 * 배포에서 도는 경로는 언제나 `after()` 쪽이다. 폴백이 있다고 해서 호출부에서
 * `after()`를 빼도 되는 것은 아니다. 폴백은 **Next 런타임이 없을 때**의 길이고,
 * 배포에는 런타임이 항상 있다.
 */
export function scheduleAfterResponse(
  label: string,
  task: () => Promise<void>,
): void {
  const guarded = async (): Promise<void> => {
    try {
      await task();
    } catch (error) {
      // 09 §2 — 실패는 로그만 남기고 포기다. 여기서 던지면 잡을 곳이 없고,
      // 잡히지 않은 거부는 인스턴스를 통째로 죽여 같은 배치의 다른 일까지 끊는다.
      console.error(`[after] ${label} 실패`, error);
    }
  };

  try {
    after(guarded);
  } catch {
    const running = guarded().finally(() => fallbackTasks.delete(running));
    fallbackTasks.add(running);
  }
}

/**
 * **폴백으로 돈 작업만** 담긴다. `after()`가 받아간 일은 여기 없다 — 그건 런타임이
 * 끝까지 책임진다.
 *
 * 즉 **배포에서는 이 집합이 언제나 비어 있다.** 요청 스코프 밖(테스트 · 스크립트)에서만
 * 채워지므로 README 「DB 접근」이 금지한 프로세스 로컬 상태(카운터 · 캐시)가 아니다 —
 * 담기는 것은 값이 아니라 진행 중인 프로미스이고, 끝나면 스스로 빠진다.
 */
const fallbackTasks = new Set<Promise<void>>();

/**
 * 폴백으로 도는 배경 작업이 끝날 때까지 기다린다. **테스트 하네스 전용이다.**
 *
 * 없으면 이런 일이 벌어진다: 테스트가 라우트를 부르고 → 폴백이 배경 작업을 띄우고 →
 * 테스트 파일이 끝나 `afterAll`이 DB를 드롭하고 → 뒤늦은 쿼리가 사라진 DB를 향해
 * 커넥션을 새로 열고 → 그 커넥션이 드롭에 끊기며 pg가 핸들러 없는 오류를 던져 **런
 * 전체가 죽는다.** 배포 경로에는 이 문제가 없다 — 거기서는 `after()`가 항상 잡고,
 * 인스턴스는 그 일이 끝나기 전에 정리되지 않는다.
 *
 * 기다리는 동안 새 작업이 붙을 수 있어 집합이 빌 때까지 돈다. `guarded`가 예외를
 * 삼키므로 이 함수는 거부하지 않는다.
 */
export async function drainAfterResponse(): Promise<void> {
  while (fallbackTasks.size > 0) {
    await Promise.all([...fallbackTasks]);
  }
}
