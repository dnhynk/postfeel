// 이메일 4종의 문구 (09 §2). 표는 그대로다:
//
//   1 manage_link    등록 직후        편지 관리 링크                  등록당 1회
//   2 first_unlock   편지가 처음 열림  누군가 편지를 열었습니다        편지당 1회
//   3 auto_hidden    신고 자동 비공개  편지가 비공개로 바뀌었습니다    발생마다
//   4 recipient_yes  yes 응답         편지를 연 사람이 답을 남겼습니다 편지당 1회
//
// **네 종 전부 링크만 담는다. 본문은 없다** (09 §2 · 안전 #20). 그래서 이 파일의 함수들이
// 받는 인자에 본문이 아예 없다 — 담고 싶어도 담을 수 없게 만드는 것이 주석보다 강하다
// (telegram.ts의 같은 규칙).
//
// 문구가 여기 모여 있는 이유는 D-007·D-023이 **문구 그 자체를 결정**했기 때문이다.
// "상대가 읽었습니다"와 "누군가 열었습니다"는 같은 사건에 대한 다른 주장이고, 전자는
// 존재하지 않는 신호다. 문구를 표면에 흩어두면 그 구분이 반드시 무너진다.

import { mail, type MailBody } from "./layout";

/** 1번 — 등록 직후. 관리 링크는 여기서만 다시 전달된다 (재발급 경로가 없다). */
export function manageLinkMail(params: {
  manageUrl: string;
  unsubscribeUrl: string;
}): MailBody {
  return mail(
    "편지 관리 링크",
    [
      "편지를 남기실 때 알림을 신청하셨습니다.",
      "",
      "이 링크로 편지 상태를 확인하거나 언제든 편지를 지울 수 있습니다.",
      params.manageUrl,
      "",
      "이 링크는 다시 보내드릴 수 없습니다. 이 메일을 지우지 말고 보관해 주세요.",
    ],
    params.unsubscribeUrl,
  );
}

/**
 * 2번 — 편지가 **처음** 열렸을 때. 편지당 한 통이다 (09 §2 · 안전 #19).
 *
 * 제목과 문구가 **"누군가 열었습니다"**인 것이 D-007이다. `상대가 읽었습니다`가 아니다 —
 * 잠긴 편지는 제3자도 열고, 열쇠를 맞춘 사람이 의도한 상대라는 보장이 없다. 그 보장이
 * 없다는 사실을 본문에서도 한 줄로 말한다. 작성자가 없는 의미를 읽지 않게 하는 것이
 * 이 메일의 유일한 위험 관리다.
 */
export function firstUnlockMail(params: {
  letterUrl: string;
  unsubscribeUrl: string;
}): MailBody {
  return mail(
    "누군가 편지를 열었습니다",
    [
      "누군가 편지를 열었습니다.",
      "열쇠를 맞춘 사람이 편지를 쓴 상대라는 보장은 없습니다.",
      "",
      params.letterUrl,
      "",
      "이 알림은 편지당 한 번만 보내드립니다.",
    ],
    params.unsubscribeUrl,
  );
}

/**
 * 3번 — 신고로 자동 비공개됐을 때. 발생마다 보낸다.
 *
 * ── 관리 링크가 없는 이유 (2026-08-15 코디네이터 확인) ──
 * 09 §2의 표는 이 메일에 `/manage/:token` 링크를 담으라고 하지만 **그 링크를 만들 수
 * 없다.** D-014가 관리 토큰 원문을 저장하지 않기로 했고(`letters.manage_token_hash`만
 * 있다), 자동 비공개는 신고 접수 뒤 서버가 혼자 실행하는 경로라 그 자리에 토큰 원문이
 * 존재하지 않는다. 원문(또는 복호 가능한 사본)을 저장하면 D-014가 막으려던 "DB 유출로
 * 전 편지 삭제 가능"이 그대로 열린다 — 메일 한 통의 편의로 열 수 있는 것이 아니다.
 *
 * 대신 **1번 메일을 가리킨다.** 1번은 등록 직후 반드시 같은 주소로 갔으므로 관리 링크는
 * 이미 그 사람의 메일함에 있다. 제목을 정확히 인용해야 검색해서 찾는다. 09 §2 문서도
 * 같은 내용으로 고쳤다.
 *
 * 신고 사유나 신고자에 대해서는 아무것도 말하지 않는다. 우리가 아는 것은 "신고가
 * 접수되어 비공개로 바뀌었다"까지다.
 */
export function autoHiddenMail(params: { unsubscribeUrl: string }): MailBody {
  return mail(
    "편지가 비공개로 바뀌었습니다",
    [
      "신고가 접수되어 편지가 비공개로 바뀌었습니다.",
      "검토 중이며, 보통 하루 안에 결과가 정해집니다.",
      "",
      "이의 제기는 이전에 보내드린 '편지 관리 링크' 메일의 링크에서 하실 수 있습니다.",
      "관리 링크는 다시 보내드릴 수 없습니다.",
    ],
    params.unsubscribeUrl,
  );
}

/**
 * 4번 — 연 사람이 `yes`로 답했을 때만. 편지당 한 통이다 (D-023 · 안전 #24).
 *
 * **주어가 "편지를 연 사람"이다.** `상대가 편지를 받았다고 확인했습니다`가 아니다 —
 * 이 응답은 실제로 일어난 사건이라 알려도 정직하지만 자기신고라, 그 사람이 의도한
 * 상대라는 함의를 넣으면 D-007이 금지한 없는 신호가 된다 (09 §2 · D-023).
 *
 * `no`·`unknown`·무응답에는 아무것도 보내지 않는다. 안 온 답을 알릴 이유가 없다.
 */
export function recipientYesMail(params: {
  letterUrl: string;
  unsubscribeUrl: string;
}): MailBody {
  return mail(
    "편지를 연 사람이 답을 남겼습니다",
    [
      '편지를 연 사람이 "나에게 온 것 같다"고 답했습니다.',
      "본인이 밝힌 것이라 편지를 쓴 상대라는 보장은 없습니다.",
      "",
      params.letterUrl,
      "",
      "이 알림은 편지당 한 번만 보내드립니다.",
    ],
    params.unsubscribeUrl,
  );
}

export type { MailBody } from "./layout";
