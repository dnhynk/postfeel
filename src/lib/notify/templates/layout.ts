// 메일 네 종의 공통 뼈대 (09 §1 · §2).
//
// ── 해지 링크가 빠질 자리를 없앤다 ──────────────────────────
// 09 §1은 "모든 발송 메일 하단. 예외 없음"이라고 못박았다. 그걸 주석으로 지키면 다섯
// 번째 메일이 생기는 날 빠진다. 그래서 **본문을 만드는 길이 이 함수 하나뿐**이고,
// 이 함수는 해지 URL 없이는 호출할 수 없다.
//
// ── 편지 본문이 들어올 자리도 없다 ──────────────────────────
// `mail()`이 받는 것은 이미 완성된 줄들이고, 렌더러들이 받는 것은 링크와 토큰뿐이다
// (index.ts). 메일은 전달·인용되며 우리 통제를 벗어나고, 편지를 지워도 메일함에 남는다
// (09 §2 · S-10과 같은 성격의 비가역 항목). 안전 테스트 #20이 이걸 고정한다.
//
// ── HTML을 만들지 않는다 ────────────────────────────────────
// 네 종 전부 "링크만" 담는 메일이라 텍스트로 표현되지 않는 것이 없다. HTML을 더하면
// 같은 문구가 두 벌이 되고, 한쪽에만 해지 링크가 빠지는 사고가 가능해진다. 순수 텍스트
// 메일에서도 URL은 대부분의 메일 클라이언트가 링크로 만들어 준다 — 09 §1의 "클릭 1회"는
// 그대로 성립한다.

export interface MailBody {
  subject: string;
  text: string;
}

/**
 * 09 §1의 문구 **그대로**다. "수신거부"가 아니다.
 *
 * 잘못 받은 사람이 자기 상황을 바로 알아보게 하는 것이 이 문구의 목적이다. "수신거부"는
 * 구독한 적 있는 사람의 언어라, 요청한 적 없는 메일을 받은 사람은 자기 얘기라고 읽지
 * 않는다.
 */
export const UNSUBSCRIBE_NOTICE = "이 알림을 요청한 적이 없다면 여기서 끄세요.";

/** 제목과 줄들에 해지 안내를 붙여 완성한다. 메일 본문이 만들어지는 유일한 자리다. */
export function mail(
  subject: string,
  lines: readonly string[],
  unsubscribeUrl: string,
): MailBody {
  return {
    subject,
    text: [...lines, "", "—", UNSUBSCRIBE_NOTICE, unsubscribeUrl, ""].join("\n"),
  };
}
