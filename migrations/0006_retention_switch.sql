-- D-031 · 파기 작업이 실패하면 신규 작성을 멈춘다 (세 번째 킬 스위치).
--
-- 출처: docs/00-decisions.md D-031 (M0 답 · 2026-08-16)
--
-- ── 왜 writing_enabled를 재사용하지 않는가 ──────────────────
-- 재사용하면 운영자가 "내가 껐다"와 "파기가 실패해서 꺼졌다"를 구분할 수 없다. 둘은
-- 대응이 정반대다 — 전자는 켜면 되고, 후자는 파기를 고치기 전에 켜면 안 된다.
--
-- 그래서 키를 나눈다. 작성 경로는 **둘 다 켜져 있을 때만** 통과시킨다.
--
-- ── 왜 작성을 막는가 ────────────────────────────────────────
-- 파기되지 않는 상태에서 데이터가 계속 쌓이면 위반 규모가 커진다. 멈추는 것이
-- 계속 받는 것보다 낫다는 판단이고, 그 판단은 D-031에 있다.
--
-- 읽기와 관리 링크는 막지 않는다. 이미 있는 편지를 못 보게 하는 것은 파기 실패와
-- 아무 관계가 없고, 작성자가 자기 편지를 지우는 길은 특히 막으면 안 된다.

insert into app_settings (key, value) values
  ('retention_healthy', 'true'::jsonb)
on conflict (key) do nothing;
