-- D-034 6 · 텔레그램에는 편지 ID를 보내지 않는다. 무작위 사건 번호를 대신 보낸다.
--
-- 출처: docs/00-decisions.md D-034 6번 · docs/09-notifications.md §3
--
-- ── 왜 컬럼이 필요한가 ──────────────────────────────────────
-- 알림에서 편지 ID를 빼면 **운영자가 새벽에 알림을 받고 어느 건인지 찾을 수 없다.**
-- 그래서 알림에 실리는 값이 신고 행에도 남아 있어야 하고, 그때 비로소 `/admin/queue`에서
-- 대조가 성립한다. 알림 문구만 좁히고 여기를 만들지 않으면 알림 자체가 쓸모없어진다.
--
-- ── 왜 편지 ID를 재사용하지 않는가 ──────────────────────────
-- 편지 ID는 추측 불가 식별자이자 공개 URL의 일부다 (04 §1-1). 그 값이 서드파티
-- 클라우드에 남으면 알림을 보는 쪽이 편지를 그대로 열 수 있고, 그게 D-034가 없애려는
-- 이전이다. 대체가 목적이므로 사건 번호는 편지 ID와 **다른 무작위 값**이다.
--
-- ── 왜 심각 카테고리만이 아니라 신고마다 만드는가 ───────────
-- 기본값으로 DB가 행과 함께 만들면 사건 번호가 없는 신고가 생기지 않는다. 앱이 나중에
-- UPDATE로 채우면 그 UPDATE가 실패한 신고만 대조 불가가 되는데, 그건 하필 **알림을 받고
-- 아무것도 못 찾는** 경우다. 실패할 수 있는 자리를 하나 없앤다.
--
-- `gen_random_uuid()`는 PG13+ 내장이고 volatile이라 ADD COLUMN이 테이블을 다시 쓰면서
-- 기존 행도 각자 다른 값을 받는다 (PG16에서 확인).
--
-- 16자 = 64비트. 대조는 사람이 눈으로 하므로 uuid 36자를 그대로 두지 않는다.

alter table reports
  add column incident_id text not null
    default substr(replace(gen_random_uuid()::text, '-', ''), 1, 16);

-- 대조에 쓰는 값이라 겹치면 안 된다. 겹치는 순간 알림이 두 신고를 가리킨다.
create unique index reports_incident_id on reports (incident_id);
